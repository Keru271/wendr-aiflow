'use client';

import React, { useState, useEffect } from 'react';
import Link from 'next/link';
import { GitPullRequest, ExternalLink, RefreshCw, CheckCircle2, ArrowRight } from 'lucide-react';

export default function PullRequestsPage() {
  const [prs, setPrs] = useState<any[]>([]);
  const [loading, setLoading] = useState(true);

  const fetchPrs = async () => {
    try {
      setLoading(true);
      const res = await fetch('/api/pull-requests');
      const data = await res.json();
      setPrs(data.pullRequests || []);
    } catch (err) {
      console.error(err);
    } finally {
      setLoading(false);
    }
  };

  useEffect(() => {
    fetchPrs();
  }, []);

  return (
    <div className="space-y-6">
      <div className="flex items-center justify-between">
        <div>
          <h2 className="text-xl font-bold text-white flex items-center gap-2">
            <GitPullRequest className="w-5 h-5 text-emerald-400" />
            <span>Autonomous Pull Requests</span>
          </h2>
          <p className="text-xs text-slate-400 mt-1">
            Pull requests generated by Google Antigravity containing full QA test evidence and rollback plans.
          </p>
        </div>

        <button
          onClick={fetchPrs}
          className="inline-flex items-center gap-1.5 px-3 py-2 rounded-lg bg-slate-800 hover:bg-slate-700 text-xs font-medium text-slate-200 transition-colors"
        >
          <RefreshCw className="w-3.5 h-3.5" />
          <span>Refresh</span>
        </button>
      </div>

      <div className="rounded-xl border border-slate-800 bg-[#0d1322]/80 overflow-hidden">
        <table className="w-full text-left text-xs">
          <thead className="bg-slate-900/60 text-slate-400 uppercase tracking-wider font-semibold border-b border-slate-800">
            <tr>
              <th className="py-3 px-5">PR #</th>
              <th className="py-3 px-5">Title</th>
              <th className="py-3 px-5">Jira Issue</th>
              <th className="py-3 px-5">Branch</th>
              <th className="py-3 px-5">Status</th>
              <th className="py-3 px-5">Created</th>
              <th className="py-3 px-5 text-right">Actions</th>
            </tr>
          </thead>
          <tbody className="divide-y divide-slate-800/60">
            {loading ? (
              <tr>
                <td colSpan={7} className="py-12 text-center text-slate-500">
                  <div className="inline-block w-6 h-6 border-2 border-emerald-500 border-t-transparent rounded-full animate-spin mb-2" />
                  <p>Loading Pull Requests...</p>
                </td>
              </tr>
            ) : prs.length === 0 ? (
              <tr>
                <td colSpan={7} className="py-12 text-center text-slate-500">
                  No Pull Requests opened yet. Trigger a live fix from the overview dashboard.
                </td>
              </tr>
            ) : (
              prs.map((pr) => (
                <tr key={pr.id} className="hover:bg-slate-800/30 transition-colors">
                  <td className="py-4 px-5 font-mono font-bold text-white">
                    #{pr.number}
                  </td>
                  <td className="py-4 px-5 text-slate-200 font-medium max-w-sm truncate">
                    {pr.title}
                  </td>
                  <td className="py-4 px-5 font-mono text-blue-400">
                    {pr.job?.bug?.jiraIssueKey || 'WEB-1024'}
                  </td>
                  <td className="py-4 px-5 text-slate-400 font-mono text-[11px]">
                    {pr.branchName}
                  </td>
                  <td className="py-4 px-5">
                    <span className="px-2.5 py-1 text-[11px] font-semibold rounded-full bg-emerald-500/10 text-emerald-400 border border-emerald-500/20">
                      {pr.status}
                    </span>
                  </td>
                  <td className="py-4 px-5 text-slate-400 font-mono">
                    {new Date(pr.createdAt).toLocaleDateString()}
                  </td>
                  <td className="py-4 px-5 text-right space-x-2">
                    <a
                      href={pr.url}
                      target="_blank"
                      rel="noreferrer"
                      className="inline-flex items-center gap-1 px-2.5 py-1.5 rounded-lg bg-slate-800 hover:bg-slate-700 text-slate-300 font-medium transition-colors"
                    >
                      <span>GitHub</span>
                      <ExternalLink className="w-3 h-3" />
                    </a>
                    <Link
                      href={`/jobs/${pr.jobId}`}
                      className="inline-flex items-center gap-1 px-2.5 py-1.5 rounded-lg bg-blue-600/20 hover:bg-blue-600/30 text-blue-300 font-medium transition-colors"
                    >
                      <span>Job</span>
                      <ArrowRight className="w-3 h-3" />
                    </Link>
                  </td>
                </tr>
              ))
            )}
          </tbody>
        </table>
      </div>
    </div>
  );
}
