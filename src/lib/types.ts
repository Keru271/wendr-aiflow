  [JobStatus.DEPLOYING_PRODUCTION]: [JobStatus.VERIFYING_PRODUCTION, JobStatus.FAILED, JobStatus.ROLLED_BACK],
  [JobStatus.VERIFYING_PRODUCTION]: [JobStatus.COMPLETED, JobStatus.ROLLED_BACK, JobStatus.FAILED],
